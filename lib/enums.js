function lookup(table, value) {
 const t = TABLES[table];
 if (!t) return null;
 return t[String(value)] || null;
}

/** Status-Klartext (geräteunabhängig). */
function statusText(v) { return lookup('StateStatus', v); }
/** Programmart-Klartext. */
function programTypeText(v) { return lookup('StateProgramType', v); }
/** Trockenstufe (Trockner). */
function dryingStepText(v) { return lookup('StateDryingStep', v); }

/** Programmname passend zum Gerätetyp. */
function programText(deviceType, programId) {
 const map = BY_TYPE[deviceType];
 return map ? lookup(map.program, programId) : null;
}
/** Phasenname passend zum Gerätetyp. */
function phaseText(deviceType, phase) {
 const map = BY_TYPE[deviceType];
 return map ? lookup(map.phase, phase) : null;
}

